/**
 * Детерминированный классификатор категории счёта по извлечённому тексту.
 *
 * Поставщики в проекте устойчиво определяются по названиям/ключевым словам,
 * поэтому классификация делается простым поиском подстрок (быстро, бесплатно,
 * без LLM-галлюцинаций). Если ни одно правило не сработало — возвращаем null,
 * вызывающий код fallback-ит на модель.
 *
 * ВАЖНО: используем toLowerCase()+includes, а не regex с \w — \w в JS без флага /u
 * НЕ матчит кириллицу, поэтому «коммунальн\w*» ломалось на «коммунальный».
 *
 * Порядок проверок выбран так, чтобы избежать коллизии «1292» у электро/тепло
 * (электричество и тепло оба по договору 1292, но разные подразделы: 1292\1\1 и 1292\2\30).
 */
import type { BillCategory } from '../../llm/prompts.js';

interface Rule {
  category: BillCategory;
  needles: string[];
}

const RULES: Rule[] = [
  // Мусор — специфичный поставщик «Нижэкология» + «обращение с … отходами».
  // (не используем «тко»/«обращени» — встречаются в обычных словах: «краткое», «обращении»)
  { category: 'garbage', needles: ['нижэкологи', 'отходами'] },
  // Содержание помещения — «Наш Дом», «Сод. и рем.», «СОИ …».
  { category: 'maintenance', needles: ['наш дом', 'сод. и рем', 'сои '] },
  // Вода — «Объединенный коммунальный оператор», водоотведение, питьевая вода, сточные воды, водоснабжение.
  // (не используем «коммунальн» — слишком широко, встречается и в других счетах)
  {
    category: 'water',
    needles: ['объединенн', 'водоотведен', 'питьев', 'сточн', 'водоканал', 'водоснабж']
  },
  // Тепло — «Автозаводская ТЭЦ», теплоэнергия, тепловая энергия, 1292\2.
  { category: 'heat', needles: ['автозаводская', 'тэц', 'теплоэнерги', 'тепловая', '1292\\2'] },
  // Электричество — «Волгаэнергосбыт», электроэнергия, 1292\1.
  { category: 'electricity', needles: ['волгаэнергосбыт', 'электроэнерги', '1292\\1'] }
];

export function classifyBillCategory(text: string): BillCategory | null {
  if (!text) return null;
  const lower = text.toLowerCase();
  for (const { category, needles } of RULES) {
    if (needles.some((n) => lower.includes(n))) return category;
  }
  return null;
}