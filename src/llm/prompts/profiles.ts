export function getSystemPromptByMode(mode: LlmMode): string {
  switch (mode) {
    case 'billsValidate':
      return BILLS_VALIDATE_SYSTEM_PROMPT;
    case 'billsOrganize':
      return BILLS_ORGANIZE_SYSTEM_PROMPT;
    default:
      return ASK_SYSTEM_PROMPT;
  }
}
