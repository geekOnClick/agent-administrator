export function getSystemPromptByMode(mode: LlmMode): string {
  switch (mode) {
    case 'bills':
      return BILLS_SYSTEM_PROMPT;
    case 'billsWithModel':
      return BILLS_WITH_MODEL_SYSTEM_PROMPT;
    default:
      return TALK_SYSTEM_PROMPT;
  }
}
